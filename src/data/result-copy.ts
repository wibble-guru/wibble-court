/** 사이트로 보낼 결과 내용 (사용자 승인 형식). 판결·확신도·점수 숫자는 넣지 않는다 (5.2 규칙 5, 5.3) */
export function resultContent(a: Analysis): ResultContent {
  const intro = RESULT_COPY.question;
  if (a.status === 'INSUFFICIENT') {
    return { intro, title: RESULT_COPY.insufficient, summary: RESULT_COPY.similar };
  }
  if (a.blended) {
    const blend = BLEND_COPY[resultId(a).replace('court-', '')];
    return { intro, title: blend.title, summary: blend.first };
  }
  const axis = AXIS_COPY[a.primary];
  return { intro, title: axis.headline, summary: axis.intro };
}
